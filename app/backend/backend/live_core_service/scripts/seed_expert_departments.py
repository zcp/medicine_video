def main():
    # 1. 检查 categories 表完整性
    missing_cats = set()
    for name, cat_name, _ in DEPARTMENT_SEED:
        cat_names_in_data = {d[1] for d in DEPARTMENT_SEED}
    # 只检查有引用的分类
    referenced_cats = sorted({d[1] for d in DEPARTMENT_SEED})
    logger.info(f"引用分类数: {len(referenced_cats)}")

    with DBSession() as db:
        # 2. 构建 category_name → category_id 映射
        rows = db.execute(text("SELECT id, name FROM categories WHERE is_active = true")).fetchall()
        cat_map = {row.name: row.id for row in rows}
        missing_in_db = [c for c in referenced_cats if c not in cat_map]
        if missing_in_db:
            logger.warning(f"⚠️ 以下分类在数据库中不存在（跳过相关种子）: {missing_in_db}")
        else:
            logger.info(f"✅ 所有 {len(referenced_cats)} 个引用分类均在 DB 中存在")

        # 3. 插入种子科室
        total = 0
        skipped_existing = 0
        skipped_no_cat = 0

        for name, cat_name, synonyms in DEPARTMENT_SEED:
            cat_id = cat_map.get(cat_name)
            if cat_id is None:
                logger.warning(f"  跳过 '{name}'：分类 '{cat_name}' 不存在")
                skipped_no_cat += 1
                continue

            # upsert: name 唯一，冲突跳过
            existing = db.execute(
                text("SELECT id FROM expert_departments WHERE name = :name"),
                {"name": name}
            ).fetchone()

            if existing:
                skipped_existing += 1
                continue

            dept_id = uuid.uuid4()
            synonyms_json = json.dumps(synonyms, ensure_ascii=False) if synonyms else "[]"

            db.execute(
                text("""
                    INSERT INTO expert_departments
                        (id, name, category_id, synonyms, is_active, is_verified, source, created_at, updated_at)
                    VALUES
                        (:id, :name, :category_id, CAST(:synonyms AS jsonb), true, true, 'seed_s4', NOW(), NOW())
                    ON CONFLICT (name) DO NOTHING
                """),
                {
                    "id": dept_id,
                    "name": name,
                    "category_id": cat_id,
                    "synonyms": synonyms_json,
                }
            )
            total += 1
            if total % 30 == 0:
                db.flush()

        db.commit()

        # 4. 报告
        final_count = db.execute(text("SELECT COUNT(*) FROM expert_departments")).scalar()
        logger.info(f"\n{'='*50}")
        logger.info(f"Sprint 4 科室种子完成")
        logger.info(f"  - 本次新增: {total} 条")
        logger.info(f"  - 跳过已有: {skipped_existing} 条")
